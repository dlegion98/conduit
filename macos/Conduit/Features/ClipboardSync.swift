import AppKit

/// Two-way clipboard. Mac → phone is automatic; phone → Mac arrives when you use
/// "Send clipboard" on the phone (Android only lets a focused app read the clipboard).
final class ClipboardSync {
    static let shared = ClipboardSync()

    private var lastChange = NSPasteboard.general.changeCount
    private var ignoreChange = -1
    private var timer: Timer?
    /// A clipboard change made by picking an item from the history: sync it, but don't record it twice.
    var historyIgnore = -1

    var enabled: Bool {
        get { UserDefaults.standard.object(forKey: "clipboardSync") as? Bool ?? true }
        set { UserDefaults.standard.set(newValue, forKey: "clipboardSync") }
    }

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.6, repeats: true) { [weak self] _ in self?.poll() }
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        guard enabled, pb.changeCount != ignoreChange else { return }
        let types = pb.types ?? []
        // Respect password managers: skip concealed / transient items (nspasteboard.org conventions).
        let skip = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]
        if types.contains(where: { skip.contains($0.rawValue) }) { return }
        let connected = AppModel.shared.connected
        let record = pb.changeCount != historyIgnore

        if let text = pb.string(forType: .string), !text.isEmpty {
            if record { AppModel.shared.recordClip(text: text, image: nil, fromPhone: false) }
            if connected { AppModel.shared.send("clipboard", ["text": text]) }
        } else if let image = NSImage(pasteboard: pb) {
            if record { AppModel.shared.recordClip(text: nil, image: image, fromPhone: false) }
            if connected, let png = image.pngData(), png.count < 8 * 1024 * 1024 {
                AppModel.shared.send("clipboard", ["image": png.base64EncodedString()])
            }
        }
    }

    func applyRemote(_ msg: [String: Any]) {
        let pb = NSPasteboard.general
        if let text = msg["text"] as? String {
            pb.clearContents()
            pb.setString(text, forType: .string)
            AppModel.shared.recordClip(text: text, image: nil, fromPhone: true)
        } else if let image = NSImage.fromBase64(msg.str("image")) {
            pb.clearContents()
            pb.writeObjects([image])
            AppModel.shared.recordClip(text: nil, image: image, fromPhone: true)
        } else {
            return
        }
        ignoreChange = pb.changeCount
        lastChange = pb.changeCount
        NotificationsBridge.shared.postInfo(title: "Clipboard from \(AppModel.shared.phoneName)", body: (msg["text"] as? String).map { String($0.prefix(80)) } ?? "Image")
    }
}
